import pandas as pd
df = pd.read_csv('eCommerce-dataset-samples/shein-products.csv')
print('Shape:', df.shape)
print('\nColumns:', list(df.columns))
print('\nNulls:')
print(df.isnull().sum())
print('\nBasic stats for numeric cols:')
for col in ['initial_price','final_price','reviews_count','rating','image_count']:
    if col in df.columns:
        print(f'  {col}: min={df[col].min()}, max={df[col].max()}, mean={df[col].mean():.2f}, median={df[col].median():.2f}')
print('\ncategory value_counts (top 15):')
print(df['category'].value_counts().head(15))
print('\nroot_category value_counts:')
print(df['root_category'].value_counts())
print('\ncolor value_counts (top 10):')
print(df['color'].value_counts().head(10))
print('\nbrand value_counts:')
print(df['brand'].value_counts().head(5))
print('\ncountry_code unique:', df['country_code'].unique())
print('\ncurrency unique:', df['currency'].unique())
print('\nin_stock distribution:')
print(df['in_stock'].value_counts())
print('\nsample size values:')
print(df['size'].value_counts().head(10))
